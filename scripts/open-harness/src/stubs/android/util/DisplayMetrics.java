package android.util;

/**
 * Métriques d'écran de démonstration : densité fixe posée par les
 * ressources — les conversions en dp en dérivent.
 */
public final class DisplayMetrics {

    /** Densité en pixels par unité dp. */
    public float density = 1.0f;

    /** Densité appliquée au corps du texte. */
    public float scaledDensity = 1.0f;
}
